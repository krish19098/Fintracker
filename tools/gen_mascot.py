"""Generates the original coin-mascot vector drawables (and SVG previews) for the 5 moods.

Run: python3 tools/gen_mascot.py [preview_dir]
Writes app/src/main/res/drawable/coin_<mood>.xml. Everything is drawn from simple shapes here.
"""
import os
import sys

GOLD, GOLD_DARK, GOLD_LIGHT, RIM = "#F6C344", "#B9822A", "#FFE08A", "#D9A23A"
INK, CHEEK, TEAR, SWEAT = "#5A3B12", "#F28B6B", "#5DADEC", "#8FD3FF"

# ₹ glyph, drawn as strokes, centred on x=32 near the top of the coin.
RUPEE = "M27.5,11.5 L36.5,11.5 M27.5,14.5 L36.5,14.5 M29,11.5 C34.2,11.5 34.2,17.6 29,17.6 L28,17.6 L34.5,23"

def eyes_open(dy=0):
    return [("fill", INK, f"M23,{33+dy} a2.6,3 0 1,0 5.2,0 a2.6,3 0 1,0 -5.2,0 Z"),
            ("fill", INK, f"M35.8,{33+dy} a2.6,3 0 1,0 5.2,0 a2.6,3 0 1,0 -5.2,0 Z"),
            ("fill", "#FFFFFF", f"M24.6,{31.8+dy} a0.9,0.9 0 1,0 1.8,0 a0.9,0.9 0 1,0 -1.8,0 Z"),
            ("fill", "#FFFFFF", f"M37.4,{31.8+dy} a0.9,0.9 0 1,0 1.8,0 a0.9,0.9 0 1,0 -1.8,0 Z")]

MOODS = {
    # Happy closed eyes, wide open grin with tongue, rosy cheeks.
    "big_smile": [
        ("stroke", INK, "M22.5,34 Q25.6,29.5 28.7,34"), ("stroke", INK, "M35.3,34 Q38.4,29.5 41.5,34"),
        ("fill", CHEEK, "M17.5,39 a3,2 0 1,0 6,0 a3,2 0 1,0 -6,0 Z"), ("fill", CHEEK, "M40.5,39 a3,2 0 1,0 6,0 a3,2 0 1,0 -6,0 Z"),
        ("fill", INK, "M23,39.5 Q32,52 41,39.5 Z"), ("fill", "#E8615A", "M27.5,45.6 Q32,42.5 36.5,45.6 Q32,49 27.5,45.6 Z"),
    ],
    # Open eyes, gentle smile.
    "smile": eyes_open() + [
        ("fill", CHEEK, "M18,40 a2.6,1.7 0 1,0 5.2,0 a2.6,1.7 0 1,0 -5.2,0 Z"), ("fill", CHEEK, "M40.8,40 a2.6,1.7 0 1,0 5.2,0 a2.6,1.7 0 1,0 -5.2,0 Z"),
        ("stroke", INK, "M25,41.5 Q32,47.5 39,41.5"),
    ],
    # Open eyes, flat mouth.
    "neutral": eyes_open() + [("stroke", INK, "M26.5,44 L37.5,44")],
    # Raised inner brows, small wavy frown, sweat drop.
    "worried": eyes_open(1) + [
        ("stroke", INK, "M22,28.5 L28,26.5"), ("stroke", INK, "M42,28.5 L36,26.5"),
        ("stroke", INK, "M26,46 Q29,43 32,45.2 Q35,43 38,46"),
        ("fill", SWEAT, "M46,24 Q49.5,30 46,32 Q42.5,30 46,24 Z"),
    ],
    # Squeezed eyes, open frown, tear streams.
    "crying": [
        ("stroke", INK, "M22.5,31 L28,33.5 L22.5,35.5"), ("stroke", INK, "M41.5,31 L36,33.5 L41.5,35.5"),
        ("stroke", INK, "M22,27 L28,29"), ("stroke", INK, "M42,27 L36,29"),
        ("fill", INK, "M26,47.5 Q26,40.5 32,40.5 Q38,40.5 38,47.5 Z"), ("fill", "#E8615A", "M28.5,47.5 Q32,44.5 35.5,47.5 Z"),
        ("fill", TEAR, "M23,37 Q25,44 23.5,52 Q21,52.5 20.5,50 Q21.5,44 23,37 Z"),
        ("fill", TEAR, "M41,37 Q39,44 40.5,52 Q43,52.5 43.5,50 Q42.5,44 41,37 Z"),
    ],
}

COIN = [
    ("fill", RIM, "M32,3 a29,29 0 1,0 0.01,0 Z"),
    ("fill", GOLD, "M32,6.5 a25.5,25.5 0 1,0 0.01,0 Z"),
    ("fill", GOLD_LIGHT, "M16,18 Q22,9 33,8.5 Q22,12 18.5,21 Z"),  # shine
]

# Big centred white ₹ for the widget / identity coin, with a darker gold shadow so it stays legible.
RUPEE_BIG = "M24,19 L40,19 M24,25 L40,25 M26.5,19 C36.5,19 36.5,31 26.5,31 L25,31 L38.5,44.5"
INNER_RING = "M32,11 a21,21 0 1,0 0.01,0 Z"

def shapes(mood):
    if mood == "rupee":
        return COIN[:2] + [("stroke-ring", GOLD_DARK, INNER_RING), ("stroke-shadow", GOLD_DARK, RUPEE_BIG), ("stroke-white", "#FFFFFF", RUPEE_BIG)]
    rupee = [("stroke-thin", GOLD_DARK, RUPEE)]
    return COIN + rupee + MOODS[mood]

def vector(mood):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           f'<!-- Original SpendSense coin mascot ({mood}); generated by tools/gen_mascot.py -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="64dp" android:height="64dp" android:viewportWidth="64" android:viewportHeight="64">']
    for kind, color, d in shapes(mood):
        if kind == "fill":
            out.append(f'    <path android:fillColor="{color}" android:pathData="{d}" />')
        else:
            w = {"stroke-thin": "1.6", "stroke-ring": "1.0", "stroke-shadow": "5.2", "stroke-white": "3.4"}.get(kind, "2.2")
            out.append(f'    <path android:fillColor="#00000000" android:strokeColor="{color}" android:strokeWidth="{w}" '
                       f'android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="{d}" />')
    out.append("</vector>")
    return "\n".join(out) + "\n"

def svg(mood):
    parts = []
    for kind, color, d in shapes(mood):
        if kind == "fill":
            parts.append(f'<path fill="{color}" d="{d}"/>')
        else:
            w = {"stroke-thin": "1.6", "stroke-ring": "1.0", "stroke-shadow": "5.2", "stroke-white": "3.4"}.get(kind, "2.2")
            parts.append(f'<path fill="none" stroke="{color}" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round" d="{d}"/>')
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="192" height="192">{"".join(parts)}</svg>'

if __name__ == "__main__":
    root = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable")
    for m in list(MOODS) + ["rupee"]:
        with open(os.path.join(root, f"coin_{m}.xml"), "w") as f:
            f.write(vector(m))
    if len(sys.argv) > 1:
        with open(os.path.join(sys.argv[1], "mascot.html"), "w") as f:
            f.write("<html><body style='margin:0;background:#eee'>" + "".join(
                f"<div style='display:inline-block;margin:8px;text-align:center;font:14px sans-serif'>{svg(m)}<br>{m}</div>" for m in list(MOODS) + ["rupee"]) + "</body></html>")
